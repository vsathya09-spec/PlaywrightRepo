// Primitive Data Types in JavaScript
//userName
var userName = "Sathya priya"; // String
console.log(userName);
console.log(typeof userName);

//organization
var organization = "CTS";    // String
console.log(organization);
console.log(typeof organization);

//contactNumber
var contactNumber = 1234567890; // Number
console.log(contactNumber);
console.log(typeof contactNumber);

//knowsAutomation
var knowsAutomation = true; // Boolean
console.log(knowsAutomation);
console.log(typeof knowsAutomation);

//usesplaywright
var usesplaywright; // Undefined
console.log(usesplaywright);
console.log(typeof usesplaywright);
